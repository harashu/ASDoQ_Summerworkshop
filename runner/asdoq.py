SUB_TO_PARENT = {sub: ch for ch, spec in CHARACTERISTICS.items() for sub in spec["subs"]}

# モデルが括弧を半角にしたり、「非曖昧性」を省いたりした場合の表記ゆれ
_SUB_ALIASES = {
    "一意性": "非曖昧性（一意性）",
    "識別性": "非曖昧性（識別性）",
}


def normalize_sub(name):
    """副特性名の表記ゆれを正規化する。公式名称にならなければ None を返す。"""
    if not name:
        return None
    s = name.strip().replace("(", "（").replace(")", "）").replace(" ", "")
    s = _SUB_ALIASES.get(s, s)
    return s if s in SUB_TO_PARENT else None


def split_candidates(value):
    """「A／B」形式の副特性を分割し、正規化した公式名称のリストを返す。

    1つでも公式名称でないものがあれば None を返す。
    """
    if not value:
        return None
    parts = [p for p in re.split(r"[／/]", value) if p.strip()]
    names = [normalize_sub(p) for p in parts]
    if not names or any(n is None for n in names):
        return None
    return names


def characteristic_spec(name):
    """判定役に渡す、担当特性の説明・副特性・測定項目のテキスト。"""
    spec = CHARACTERISTICS[name]
    lines = [f"品質特性：{name}", f"説明：{spec['desc']}", ""]
    for sub, sub_spec in spec["subs"].items():
        lines.append(f"■ 品質副特性：{sub}")
        lines.append(f"  説明：{sub_spec['desc']}")
        lines.append("  測定項目：")
        lines.extend(f"  - {item}" for item in sub_spec["items"])
        lines.append("")
    return "\n".join(lines).strip()
